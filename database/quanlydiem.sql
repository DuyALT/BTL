SET NAMES utf8mb4;   -- đảm bảo đọc file đúng tiếng Việt
CREATE DATABASE IF NOT EXISTS quanlydiem CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE quanlydiem;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS lich_su_diem, diem, dang_ky, lop_hoc_phan, mon_hoc, hoc_ky, sinh_vien, giang_vien, users;
SET FOREIGN_KEY_CHECKS = 1;

-- 1. Tài khoản đăng nhập + phân quyền
CREATE TABLE users (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,              -- mật khẩu đã băm bằng password_hash()
    ho_ten        VARCHAR(100) NOT NULL,
    email         VARCHAR(100) NULL,
    role          ENUM('admin','giangvien','sinhvien') NOT NULL,
    trang_thai    ENUM('active','locked') NOT NULL DEFAULT 'active',
    created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 2. Giảng viên (1-1 với users)
CREATE TABLE giang_vien (
    id       INT AUTO_INCREMENT PRIMARY KEY,
    ma_gv    VARCHAR(20)  NOT NULL UNIQUE,
    ho_ten   VARCHAR(100) NOT NULL,
    email    VARCHAR(100) NULL,
    khoa     VARCHAR(100) NULL,
    user_id  INT NULL UNIQUE,
    CONSTRAINT fk_gv_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- 3. Sinh viên (1-1 với users)
CREATE TABLE sinh_vien (
    id         INT AUTO_INCREMENT PRIMARY KEY,
    ma_sv      VARCHAR(20)  NOT NULL UNIQUE,
    ho_ten     VARCHAR(100) NOT NULL,
    ngay_sinh  DATE NULL,
    gioi_tinh  ENUM('Nam','Nữ') NULL,
    lop        VARCHAR(20)  NOT NULL,                  -- lớp sinh hoạt (hành chính)
    user_id    INT NULL UNIQUE,
    CONSTRAINT fk_sv_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- 4. Học kỳ - năm học
CREATE TABLE hoc_ky (
    id       INT AUTO_INCREMENT PRIMARY KEY,
    ma_hk    VARCHAR(10) NOT NULL UNIQUE,              -- vd: 20251 = HK1 năm 2025-2026
    ten_hk   VARCHAR(50) NOT NULL,
    nam_hoc  VARCHAR(9)  NOT NULL                      -- vd: 2025-2026
) ENGINE=InnoDB;

-- 5. Môn học + cấu hình trọng số tính điểm (tổng trọng số = 100%)
CREATE TABLE mon_hoc (
    id          INT AUTO_INCREMENT PRIMARY KEY,
    ma_mon      VARCHAR(20)  NOT NULL UNIQUE,
    ten_mon     VARCHAR(150) NOT NULL,
    so_tin_chi  TINYINT UNSIGNED NOT NULL CHECK (so_tin_chi BETWEEN 1 AND 10),
    ts_cc       TINYINT UNSIGNED NOT NULL DEFAULT 10,  -- % chuyên cần
    ts_kt       TINYINT UNSIGNED NOT NULL DEFAULT 20,  -- % kiểm tra
    ts_th       TINYINT UNSIGNED NOT NULL DEFAULT 20,  -- % thực hành
    ts_thi      TINYINT UNSIGNED NOT NULL DEFAULT 50,  -- % thi kết thúc học phần
    diem_dat    DECIMAL(3,1) NOT NULL DEFAULT 4.0,     -- ngưỡng điểm tổng kết để Đạt
    CONSTRAINT chk_tong_trong_so CHECK (ts_cc + ts_kt + ts_th + ts_thi = 100),
    CONSTRAINT chk_diem_dat CHECK (diem_dat BETWEEN 0 AND 10)
) ENGINE=InnoDB;

-- 6. Lớp học phần (môn học mở trong 1 học kỳ, do 1 giảng viên phụ trách)
CREATE TABLE lop_hoc_phan (
    id             INT AUTO_INCREMENT PRIMARY KEY,
    ma_lhp         VARCHAR(30) NOT NULL UNIQUE,
    mon_hoc_id     INT NOT NULL,
    hoc_ky_id      INT NOT NULL,
    giang_vien_id  INT NULL,
    si_so_toi_da   INT NOT NULL DEFAULT 60,
    CONSTRAINT fk_lhp_mon FOREIGN KEY (mon_hoc_id)    REFERENCES mon_hoc(id),
    CONSTRAINT fk_lhp_hk  FOREIGN KEY (hoc_ky_id)     REFERENCES hoc_ky(id),
    CONSTRAINT fk_lhp_gv  FOREIGN KEY (giang_vien_id) REFERENCES giang_vien(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- 7. Sinh viên thuộc lớp học phần (n-n giữa sinh_vien và lop_hoc_phan)
CREATE TABLE dang_ky (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    lhp_id        INT NOT NULL,
    sinh_vien_id  INT NOT NULL,
    UNIQUE KEY uq_dk (lhp_id, sinh_vien_id),
    CONSTRAINT fk_dk_lhp FOREIGN KEY (lhp_id)       REFERENCES lop_hoc_phan(id) ON DELETE CASCADE,
    CONSTRAINT fk_dk_sv  FOREIGN KEY (sinh_vien_id) REFERENCES sinh_vien(id)
) ENGINE=InnoDB;

-- 8. Điểm của mỗi sinh viên trong mỗi lớp học phần (1-1 với dang_ky)
CREATE TABLE diem (
    id          INT AUTO_INCREMENT PRIMARY KEY,
    dang_ky_id  INT NOT NULL UNIQUE,
    cc          DECIMAL(3,1) NULL CHECK (cc  BETWEEN 0 AND 10),
    kt          DECIMAL(3,1) NULL CHECK (kt  BETWEEN 0 AND 10),
    th          DECIMAL(3,1) NULL CHECK (th  BETWEEN 0 AND 10),
    thi         DECIMAL(3,1) NULL CHECK (thi BETWEEN 0 AND 10),
    tong_ket    DECIMAL(3,1) NULL,                     -- hệ thống tự tính
    ket_qua     ENUM('Đạt','Không đạt') NULL,         -- hệ thống tự xác định
    updated_by  INT NULL,
    updated_at  DATETIME NULL,
    CONSTRAINT fk_diem_dk   FOREIGN KEY (dang_ky_id) REFERENCES dang_ky(id) ON DELETE CASCADE,
    CONSTRAINT fk_diem_user FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- 9. Lịch sử chỉnh sửa điểm (mỗi cột điểm thay đổi = 1 dòng)
CREATE TABLE lich_su_diem (
    id           INT AUTO_INCREMENT PRIMARY KEY,
    diem_id      INT NOT NULL,
    nguoi_sua    INT NULL,
    cot          VARCHAR(10) NOT NULL,                 -- cc / kt / th / thi
    gia_tri_cu   DECIMAL(3,1) NULL,
    gia_tri_moi  DECIMAL(3,1) NULL,
    ly_do        VARCHAR(255) NULL,
    thoi_gian    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ls_diem FOREIGN KEY (diem_id)   REFERENCES diem(id) ON DELETE CASCADE,
    CONSTRAINT fk_ls_user FOREIGN KEY (nguoi_sua) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE INDEX idx_ls_time ON lich_su_diem(thoi_gian);
CREATE INDEX idx_sv_lop  ON sinh_vien(lop);

